  page.setDefaultTimeout(20000);
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error' && /cannot contain|descendant|hydration|unique.*key|Invalid hook/i.test(m.text())) errors.push(m.text()); });
