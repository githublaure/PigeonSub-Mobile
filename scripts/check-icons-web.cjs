  assert.equal(await stored('demo'), null, 'draft import is not saved before submit');
  await snap('form', formIcon);
  await page.getByRole('button', { name: 'Enregistrer', exact: true }).click();
  await page.waitForURL(/\/subscriptions\/1$/);
  await page.getByTestId('subscription-icon-1').waitFor();
  const original = await stored('demo');
  assert(original.startsWith('data:image/jpeg;base64,') && original.length < 180000);
  await open('/subscriptions');
  await page.getByTestId('subscription-card-1').getByTestId('subscription-icon-1').waitFor();
